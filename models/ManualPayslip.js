import mongoose from 'mongoose';

const manualPayslipSchema = new mongoose.Schema({
  organizationId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Organization',
    required: true,
    index: true
  },
  // Company details
  companyName: {
    type: String,
    required: true
  },
  companyAddress: {
    type: String,
    required: true
  },
  companyPhone: {
    type: String,
    required: true
  },
  companyLogo: {
    type: String // URL to uploaded logo
  },
  // Bank details
  bankAccountName: {
    type: String
  },
  bankAccountNumber: {
    type: String
  },
  bankTransitNumber: {
    type: String
  },
  // Employee details (not linked to Employee model)
  employeeName: {
    type: String,
    required: true
  },
  employeeEmail: {
    type: String
  },
  employeeAddress: {
    type: String
  },
  employeePosition: {
    type: String
  },
  province: {
    type: String,
    required: true
  },
  // Pay period
  payPeriodFrom: {
    type: Date,
    required: true
  },
  payPeriodTo: {
    type: Date,
    required: true
  },
  payFrequency: {
    type: String,
    default: 'MONTHLY_12PP'
  },
  // Salary details
  grossSalary: {
    type: Number,
    required: true
  },
  federalTax: {
    type: Number,
    required: true
  },
  provincialTax: {
    type: Number,
    required: true
  },
  totalTax: {
    type: Number,
    required: true
  },
  cpp: {
    type: Number,
    required: true
  },
  cpp2: {
    type: Number,
    default: 0
  },
  ei: {
    type: Number,
    required: true
  },
  totalDeductions: {
    type: Number,
    required: true
  },
  netPay: {
    type: Number,
    required: true
  },
  // Template used
  templateId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'PayslipTemplate',
    required: true
  },
  templateName: {
    type: String,
    required: true
  },
  // Generated PDF
  pdfUrl: {
    type: String,
    required: true
  },
  // Generated by
  generatedBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true
  },
  // Status
  status: {
    type: String,
    enum: ['generated', 'downloaded', 'sent'],
    default: 'generated'
  }
}, {
  timestamps: true
});

// Indexes for faster queries
manualPayslipSchema.index({ organizationId: 1, createdAt: -1 });
manualPayslipSchema.index({ employeeName: 1 });
manualPayslipSchema.index({ generatedBy: 1 });

const ManualPayslip = mongoose.model('ManualPayslip', manualPayslipSchema);

export default ManualPayslip;
