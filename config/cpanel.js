/**
 * Shared cPanel configuration.
 *
 * NexaFlow uses ONE cPanel account (the "nexaflow" API token) to provision and
 * manage email accounts for ALL organizations. Individual orgs no longer need
 * to configure cPanel themselves — an org admin just creates mailboxes and the
 * shared account below is used.
 *
 * An org MAY still override any of these by saving its own cPanel settings on
 * the Organization document; `resolveCpanelConfig` merges org-specific values
 * over the shared defaults.
 *
 * Override any value via environment variables (recommended for production).
 * NOTE: the API token is a secret — prefer CPANEL_API_TOKEN in the environment.
 */
export const SHARED_CPANEL = {
  host: process.env.CPANEL_HOST || 'c8.my-control-panel.com',
  port: Number(process.env.CPANEL_PORT) || 2083,
  // The cPanel account USERNAME that owns the API token. Required for auth
  // (header is `cpanel <username>:<token>`). Set CPANEL_USERNAME in the env.
  username: process.env.CPANEL_USERNAME || 'sparkle1',
  apiToken: process.env.CPANEL_API_TOKEN || 'JLX7ZZ9ADMYNTCFX3EFFMDU7RJVKFNLQ',
  // Domain that new mailboxes are created under (user@domain).
  domain: process.env.CPANEL_DOMAIN || 'sparklextechnologies.com',
};

// Mail-server infrastructure (discovered from the live host). An organization
// that wants email on their OWN domain adds these to their DNS / registrar.
export const MAIL_INFRA = {
  serverHost: process.env.CPANEL_HOST || 'c8.my-control-panel.com',
  serverIp: process.env.CPANEL_SERVER_IP || '198.251.89.220',
  nameservers: (process.env.CPANEL_NAMESERVERS || 'ns1.my-control-panel.com,ns2.my-control-panel.com')
    .split(',').map((s) => s.trim()).filter(Boolean),
  webmailPort: 2096,
};

/**
 * Build the DNS records an organization must add at their registrar so that
 * `domain` sends/receives email through the shared cPanel mail server.
 * Two options: (A) delegate nameservers to the host, or (B) keep their own DNS
 * and add the individual records below.
 *
 * DKIM is generated per-domain by cPanel AFTER the domain is provisioned, so it
 * is returned as a placeholder here and can be filled from the cPanel API once
 * the account username is configured.
 *
 * @param {string} domain
 * @returns {{ nameservers: string[], records: Array<{type,host,value,priority?,note?}> }}
 */
export function getDnsRecords(domain) {
  const d = (domain || 'yourdomain.com').toLowerCase().trim();
  return {
    nameservers: MAIL_INFRA.nameservers,
    serverIp: MAIL_INFRA.serverIp,
    mailHost: `mail.${d}`,
    records: [
      { type: 'A',   host: `mail.${d}`, value: MAIL_INFRA.serverIp, note: 'Points your mail subdomain to the mail server.' },
      { type: 'MX',  host: d, value: `mail.${d}`, priority: 0, note: 'Routes inbound email to the mail server.' },
      { type: 'TXT', host: d, value: `v=spf1 +a +mx +ip4:${MAIL_INFRA.serverIp} ~all`, note: 'SPF — authorizes the server to send mail.' },
      { type: 'TXT', host: `default._domainkey.${d}`, value: 'v=DKIM1; k=rsa; p=<generated after domain is provisioned>', note: 'DKIM — signs outgoing mail (auto-generated by the server).' },
      { type: 'TXT', host: `_dmarc.${d}`, value: 'v=DMARC1; p=none;', note: 'DMARC policy (optional but recommended).' },
      { type: 'CNAME', host: `autodiscover.${d}`, value: MAIL_INFRA.serverHost, note: 'Lets mail clients auto-configure (optional).' },
    ],
  };
}

/**
 * Merge an organization's own cPanel settings over the shared defaults.
 * Org-specific non-empty values win; otherwise the shared account is used.
 *
 * @param {Object} org - Organization document (may have cpanel* fields)
 * @returns {{ cpanelHost, cpanelPort, cpanelUsername, cpanelApiToken, cpanelDomain }}
 */
export function resolveCpanelConfig(org = {}) {
  return {
    cpanelHost: org.cpanelHost || SHARED_CPANEL.host,
    cpanelPort: org.cpanelPort || SHARED_CPANEL.port,
    cpanelUsername: org.cpanelUsername || SHARED_CPANEL.username,
    cpanelApiToken: org.cpanelApiToken || SHARED_CPANEL.apiToken,
    cpanelDomain: org.cpanelDomain || SHARED_CPANEL.domain,
  };
}

/**
 * Build the base webmail URL for the shared/organization cPanel host, so the
 * ERP can offer a "Open Webmail" entry point for a mailbox.
 *
 * @param {Object} org - Organization document
 * @returns {string} e.g. https://c8.my-control-panel.com:2096
 */
export function getWebmailUrl(org = {}) {
  const cfg = resolveCpanelConfig(org);
  return `https://${cfg.cpanelHost}:2096`;
}
